"""PostgreSQL schema shared by the application and the SQLite migration script.

Uploaded files are stored as BYTEA so no local filesystem state is required:
Render containers have ephemeral disks, but the managed database persists.
"""

SCHEMA_STATEMENTS = (
    """
    CREATE TABLE IF NOT EXISTS users (
        sub TEXT PRIMARY KEY,
        email TEXT NOT NULL,
        name TEXT NOT NULL DEFAULT '',
        picture TEXT NOT NULL DEFAULT '',
        created_at BIGINT NOT NULL,
        last_login BIGINT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS app_sessions (
        token TEXT PRIMARY KEY,
        user_sub TEXT NOT NULL,
        expires_at BIGINT NOT NULL,
        created_at BIGINT NOT NULL,
        FOREIGN KEY (user_sub) REFERENCES users(sub) ON DELETE CASCADE
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS conversations (
        id TEXT PRIMARY KEY,
        user_sub TEXT NOT NULL,
        title TEXT NOT NULL,
        created_at BIGINT NOT NULL,
        updated_at BIGINT NOT NULL,
        FOREIGN KEY (user_sub) REFERENCES users(sub) ON DELETE CASCADE
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        conversation_id TEXT NOT NULL,
        role TEXT NOT NULL,
        content TEXT NOT NULL,
        attachments TEXT NOT NULL DEFAULT '[]',
        created_at BIGINT NOT NULL,
        FOREIGN KEY (conversation_id) REFERENCES conversations(id)
            ON DELETE CASCADE
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS files (
        id TEXT PRIMARY KEY,
        user_sub TEXT NOT NULL,
        name TEXT NOT NULL,
        mime_type TEXT NOT NULL,
        size INTEGER NOT NULL,
        data BYTEA NOT NULL,
        extracted_text TEXT NOT NULL DEFAULT '',
        created_at BIGINT NOT NULL,
        FOREIGN KEY (user_sub) REFERENCES users(sub) ON DELETE CASCADE
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_conversations_user ON conversations(user_sub, updated_at DESC)",
    "CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages(conversation_id, id)",
    "CREATE INDEX IF NOT EXISTS idx_files_user ON files(user_sub, created_at DESC)",
)
